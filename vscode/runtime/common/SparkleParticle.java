package __PACKAGE__;

import java.util.List;
import net.minecraft.client.Minecraft;
import net.minecraft.client.multiplayer.ClientLevel;
import net.minecraft.client.particle.ParticleRenderType;
import net.minecraft.client.particle.TextureSheetParticle;
import net.minecraft.client.renderer.texture.TextureAtlas;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.phys.Vec3;

/**
 * A particle of a Sparkle emitter: gravity, collision with bounce, size, light and events (death, time, location).
 * Its textures come from the particle atlas: every image of "assets/&lt;namespace&gt;/textures/particle/" is in it.
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
public final class SparkleParticle extends TextureSheetParticle {
    private final SparkleSystemParticle system;
    private final int index;
    private final SparkleEmitter emitter;
    private final float randomScale;
    private final TextureAtlasSprite[] sprites;
    /** Inside the zone of its location event at the last tick (the event is sent when it enters). */
    private boolean inZone;
    private boolean touching;

    SparkleParticle(ClientLevel level, SparkleSystemParticle system, int index, SparkleEmitter emitter,
            double x, double y, double z, double xd, double yd, double zd, int lifetime) {
        super(level, x, y, z);
        this.system = system;
        this.index = index;
        this.emitter = emitter;
        this.xd = xd;
        this.yd = yd;
        this.zd = zd;
        this.lifetime = Math.max(1, lifetime);
        this.hasPhysics = false;
        this.gravity = 0.0f;
        this.randomScale = emitter.scaleMin + random.nextFloat() * (emitter.scaleMax - emitter.scaleMin);
        this.quadSize = size(0.0f);
        setColor(emitter.red, emitter.green, emitter.blue);
        this.sprites = sprites(emitter);
        setSprite(emitter.animated ? sprites[0] : sprites[random.nextInt(sprites.length)]);
        this.inZone = emitter.locationChance >= 0.0 && system.inZone(emitter, x, y, z);
    }

    /** The particle atlas ("TextureAtlas.LOCATION_PARTICLES", deprecated in 1.21: its path works on every version). */
    private static final ResourceLocation PARTICLE_ATLAS = ResourceLocation.tryParse("minecraft:textures/atlas/particles.png");

    /** The sprites of the textures of the emitter (a missing texture shows the purple and black square). */
    private static TextureAtlasSprite[] sprites(SparkleEmitter emitter) {
        TextureAtlas atlas = (TextureAtlas) Minecraft.getInstance().getTextureManager().getTexture(PARTICLE_ATLAS);
        TextureAtlasSprite[] sprites = new TextureAtlasSprite[emitter.textures.length];
        for (int i = 0; i < sprites.length; i++) {
            sprites[i] = atlas.getSprite(emitter.textures[i]);
        }

        return sprites;
    }

    @Override
    public void tick() {
        xo = x;
        yo = y;
        zo = z;
        if (age++ >= lifetime) {
            die();
            return;
        }

        if (emitter.animated && sprites.length > 1) {
            setSprite(sprites[Math.min(sprites.length - 1, age * sprites.length / lifetime)]);
        }

        xd += emitter.gravityX;
        yd += emitter.gravityY;
        zd += emitter.gravityZ;
        double mx = xd, my = yd, mz = zd;
        if (emitter.collides) {
            Vec3 moved = Entity.collideBoundingBox(null, new Vec3(xd, yd, zd), getBoundingBox(), level, List.of());
            mx = moved.x;
            my = moved.y;
            mz = moved.z;
            boolean hit = mx != xd || my != yd || mz != zd;
            // One event when the particle starts touching a block, not at every tick it rests on it.
            if (hit && !touching && emitter.collisionChance >= 0.0) {
                system.onEvent(index, SparkleEmitter.COLLISION, x + mx, y + my, z + mz, xd, yd, zd);
            }

            touching = hit;
            if (hit && emitter.diesOnCollision) {
                setPos(x + mx, y + my, z + mz);
                die();
                return;
            }

            // Bounce: the speed stopped by a block goes back the other way.
            if (mx != xd) {
                xd = -xd * emitter.bounce;
            }

            if (my != yd) {
                yd = -yd * emitter.bounce;
            }

            if (mz != zd) {
                zd = -zd * emitter.bounce;
            }
        }

        setPos(x + mx, y + my, z + mz);
        if (emitter.timeChance >= 0.0 && (emitter.timeRepeats ? age % emitter.timeTicks == 0 : age == emitter.timeTicks)) {
            system.onEvent(index, SparkleEmitter.TIME, x, y, z, xd, yd, zd);
        }

        if (emitter.locationChance >= 0.0) {
            boolean inside = system.inZone(emitter, x, y, z);
            if (inside && !inZone) {
                system.onEvent(index, SparkleEmitter.LOCATION, x, y, z, xd, yd, zd);
            }

            inZone = inside;
        }
    }

    private void die() {
        remove();
        system.onDeath(index, x, y, z, xd, yd, zd);
    }

    /** Half of the size of the square, in blocks. */
    private float size(float partialTick) {
        float size;
        if (emitter.scaleMode == SparkleEmitter.OVER_LIFE) {
            float progress = Math.min(1.0f, (age + partialTick) / lifetime);
            size = emitter.scaleStart + (emitter.scaleEnd - emitter.scaleStart) * progress;
        } else if (emitter.scaleMode == SparkleEmitter.RANDOM) {
            size = randomScale;
        } else {
            size = emitter.scaleValue;
        }

        return size / 2.0f;
    }

    @Override
    public float getQuadSize(float partialTick) {
        return size(partialTick);
    }

    @Override
    protected int getLightColor(float partialTick) {
        return emitter.glow ? 0xF000F0 : super.getLightColor(partialTick);
    }

    @Override
    public ParticleRenderType getRenderType() {
        return emitter.translucent ? ParticleRenderType.PARTICLE_SHEET_TRANSLUCENT : ParticleRenderType.PARTICLE_SHEET_OPAQUE;
    }
}
