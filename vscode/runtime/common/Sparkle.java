package __PACKAGE__;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.Level;

/**
 * Sparkle particle systems: play a system made in the Sparkle editor (assets/&lt;mod&gt;/sparkle/&lt;name&gt;.json)
 * from the server, for the players nearby. A system is named "mymod:fire", or "fire" for a system of this mod.
 * The message travels with the particle packet of the game: it works the same on Forge, NeoForge and Fabric.
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
public final class Sparkle {
    /** The particle type that carries the systems to the players. */
    public static final SparkleParticleType TYPE = new SparkleParticleType();

    /** Its name in the registry of the particle types: "mymod:sparkle". */
    public static final String TYPE_NAME = "sparkle";

    /** Plays a system at a point. */
    public static void play(Level level, String system, double x, double y, double z) {
        play(level, system, x, y, z, null);
    }

    /** Plays a system at a point, with values for its user parameters (see {@link SparkleParameters}). */
    public static void play(Level level, String system, double x, double y, double z, SparkleParameters parameters) {
        send(level, new SparkleOptions(key(system), -1, SparkleOptions.PLAY, list(parameters)), x, y, z);
    }

    /** Plays a system at the center of a block. */
    public static void play(Level level, String system, BlockPos position) {
        play(level, system, position, null);
    }

    public static void play(Level level, String system, BlockPos position, SparkleParameters parameters) {
        if (position != null) {
            play(level, system, position.getX() + 0.5, position.getY() + 0.5, position.getZ() + 0.5, parameters);
        }
    }

    /** Plays a system on an entity: it follows the entity until it is stopped or the entity leaves. */
    public static void playOn(Entity entity, String system) {
        playOn(entity, system, null);
    }

    public static void playOn(Entity entity, String system, SparkleParameters parameters) {
        if (entity != null) {
            send(entity.level(), new SparkleOptions(key(system), entity.getId(), SparkleOptions.PLAY, list(parameters)), entity.getX(), entity.getY(), entity.getZ());
        }
    }

    /** Stops the systems played on an entity: their particles end their life. */
    public static void stopOn(Entity entity) {
        if (entity != null) {
            send(entity.level(), new SparkleOptions("", entity.getId(), SparkleOptions.STOP, List.of()), entity.getX(), entity.getY(), entity.getZ());
        }
    }

    /** Stops the systems playing around a point, up to the radius (in blocks). */
    public static void stopAt(Level level, double x, double y, double z, double radius) {
        send(level, new SparkleOptions("", -1, SparkleOptions.STOP, List.of(new SparkleOptions.Parameter("radius", Math.max(0.0, radius), 0.0, 0.0))), x, y, z);
    }

    /** "mymod:fire" for "fire"; a name with a namespace stays as it is. */
    static String key(String system) {
        if (system == null || system.isBlank()) {
            return "";
        }

        String trimmed = system.trim();
        return trimmed.indexOf(':') < 0 ? SparkleConfig.MOD_ID + ":" + trimmed : trimmed;
    }

    private static List<SparkleOptions.Parameter> list(SparkleParameters parameters) {
        List<SparkleOptions.Parameter> list = new ArrayList<>();
        if (parameters != null) {
            for (Map.Entry<String, double[]> value : parameters.values().entrySet()) {
                double[] v = value.getValue();
                list.add(new SparkleOptions.Parameter(value.getKey(), v[0], v[1], v[2]));
            }
        }

        return list;
    }

    /** The server sends the particle to the players nearby (on the client, nothing happens: play from the server). */
    private static void send(Level level, SparkleOptions options, double x, double y, double z) {
        if (level instanceof ServerLevel server && (options.action() == SparkleOptions.STOP || !options.system().isEmpty())) {
            server.sendParticles(options, x, y, z, 0, 0.0, 0.0, 0.0, 0.0);
        }
    }

    private Sparkle() {
    }
}
