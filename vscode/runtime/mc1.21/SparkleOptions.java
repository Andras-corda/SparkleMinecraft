package __PACKAGE__;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import java.util.List;
import net.minecraft.core.particles.ParticleOptions;
import net.minecraft.core.particles.ParticleType;
import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.ByteBufCodecs;
import net.minecraft.network.codec.StreamCodec;

/**
 * What the server sends to play or stop a Sparkle system (Minecraft 1.20.5 and later): the system, the entity it
 * follows (-1: none), the action and the values of its user parameters.
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
public record SparkleOptions(String system, int entity, int action, List<Parameter> parameters) implements ParticleOptions {
    public static final int PLAY = 0;
    public static final int STOP = 1;

    /** The value of a user parameter: x for a number, x y z for a vector or a color. */
    public record Parameter(String name, double x, double y, double z) {
        public static final Codec<Parameter> CODEC = RecordCodecBuilder.create(instance -> instance.group(
                Codec.STRING.fieldOf("name").forGetter(Parameter::name),
                Codec.DOUBLE.fieldOf("x").forGetter(Parameter::x),
                Codec.DOUBLE.fieldOf("y").forGetter(Parameter::y),
                Codec.DOUBLE.fieldOf("z").forGetter(Parameter::z)).apply(instance, Parameter::new));

        public static final StreamCodec<RegistryFriendlyByteBuf, Parameter> STREAM_CODEC = StreamCodec.composite(
                ByteBufCodecs.STRING_UTF8, Parameter::name,
                ByteBufCodecs.DOUBLE, Parameter::x,
                ByteBufCodecs.DOUBLE, Parameter::y,
                ByteBufCodecs.DOUBLE, Parameter::z,
                Parameter::new);
    }

    public static final MapCodec<SparkleOptions> CODEC = RecordCodecBuilder.mapCodec(instance -> instance.group(
            Codec.STRING.fieldOf("system").forGetter(SparkleOptions::system),
            Codec.INT.optionalFieldOf("entity", -1).forGetter(SparkleOptions::entity),
            Codec.INT.optionalFieldOf("action", PLAY).forGetter(SparkleOptions::action),
            Parameter.CODEC.listOf().optionalFieldOf("parameters", List.of()).forGetter(SparkleOptions::parameters)).apply(instance, SparkleOptions::new));

    public static final StreamCodec<RegistryFriendlyByteBuf, SparkleOptions> STREAM_CODEC = StreamCodec.composite(
            ByteBufCodecs.STRING_UTF8, SparkleOptions::system,
            ByteBufCodecs.VAR_INT, SparkleOptions::entity,
            ByteBufCodecs.VAR_INT, SparkleOptions::action,
            Parameter.STREAM_CODEC.apply(ByteBufCodecs.list()), SparkleOptions::parameters,
            SparkleOptions::new);

    @Override
    public ParticleType<?> getType() {
        return Sparkle.TYPE;
    }
}
