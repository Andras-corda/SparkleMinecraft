package __PACKAGE__;

import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.ResourceManagerReloadListener;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.neoforge.client.event.AddClientReloadListenersEvent;
import net.neoforged.neoforge.client.event.RegisterParticleProvidersEvent;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;

/**
 * The client side of Sparkle on NeoForge: what a received Sparkle particle does, and the reload of the systems with the
 * resources (F3+T).
 * NeoForge 1.21.4 and later: the bus is found from the event, and reload listeners have a name (this file replaces the
 * one of neoforge).
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
@EventBusSubscriber(modid = SparkleConfig.MOD_ID, value = Dist.CLIENT)
public final class SparkleNeoForgeClient {
    private SparkleNeoForgeClient() {
    }

    @SubscribeEvent
    public static void registerProviders(RegisterParticleProvidersEvent event) {
        event.registerSpecial(Sparkle.TYPE, SparkleClient.provider());
    }

    @SubscribeEvent
    public static void registerReloadListeners(AddClientReloadListenersEvent event) {
        event.addListener(ResourceLocation.tryParse(SparkleConfig.MOD_ID + ":sparkle_systems"),
                (ResourceManagerReloadListener) manager -> SparkleClient.reload());
    }
}
