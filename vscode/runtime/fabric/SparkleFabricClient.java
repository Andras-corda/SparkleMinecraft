package __PACKAGE__;

import net.fabricmc.api.ClientModInitializer;
import net.fabricmc.fabric.api.client.particle.v1.ParticleFactoryRegistry;
import net.fabricmc.fabric.api.resource.ResourceManagerHelper;
import net.fabricmc.fabric.api.resource.SimpleSynchronousResourceReloadListener;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.resources.ResourceManager;

/**
 * The client side of Sparkle on Fabric: what a received Sparkle particle does, and the reload of the systems with the
 * resources (F3+T). An entry point of "client" in fabric.mod.json: the plugin adds it there.
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
public final class SparkleFabricClient implements ClientModInitializer {
    @Override
    public void onInitializeClient() {
        ParticleFactoryRegistry.getInstance().register(Sparkle.TYPE, SparkleClient.provider());
        ResourceManagerHelper.get(PackType.CLIENT_RESOURCES).registerReloadListener(new SimpleSynchronousResourceReloadListener() {
            @Override
            public ResourceLocation getFabricId() {
                return ResourceLocation.tryParse(SparkleConfig.MOD_ID + ":sparkle_systems");
            }

            @Override
            public void onResourceManagerReload(ResourceManager manager) {
                SparkleClient.reload();
            }
        });
    }
}
