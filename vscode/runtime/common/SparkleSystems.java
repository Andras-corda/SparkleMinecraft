package __PACKAGE__;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.Reader;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import net.minecraft.client.Minecraft;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * The Sparkle systems of the resource packs, read on the client from "assets/&lt;namespace&gt;/sparkle/&lt;name&gt;.json"
 * the first time they play and forgotten when the resources are reloaded (F3+T), so an edited file plays at once.
 * Generated by the Sparkle plugin: do not edit, it is written again when the runtime is updated.
 */
public final class SparkleSystems {
    private static final Logger LOGGER = LoggerFactory.getLogger("Sparkle");
    private static final Map<String, Optional<SparkleSystem>> CACHE = new ConcurrentHashMap<>();

    private SparkleSystems() {
    }

    /** The system "namespace:name", or null when there is no such file or it cannot be read (it is logged once). */
    public static SparkleSystem get(String key) {
        return CACHE.computeIfAbsent(key, SparkleSystems::load).orElse(null);
    }

    /** Forgets every system: called when the resources are reloaded. */
    public static void clear() {
        CACHE.clear();
    }

    private static Optional<SparkleSystem> load(String key) {
        ResourceLocation name = ResourceLocation.tryParse(key);
        ResourceLocation file = name == null ? null : ResourceLocation.tryParse(name.getNamespace() + ":sparkle/" + name.getPath() + ".json");
        if (file == null) {
            LOGGER.warn("Sparkle system '{}': not a valid name.", key);
            return Optional.empty();
        }

        Optional<Resource> resource = Minecraft.getInstance().getResourceManager().getResource(file);
        if (resource.isEmpty()) {
            LOGGER.warn("Sparkle system '{}': no file assets/{}/{}.", key, file.getNamespace(), file.getPath());
            return Optional.empty();
        }

        try (Reader reader = resource.get().openAsReader()) {
            JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
            if (root.has("properties") && root.get("properties").isJsonObject()) {
                root = root.getAsJsonObject("properties");
            }

            return Optional.of(read(root));
        } catch (Exception exception) {
            LOGGER.warn("Sparkle system '{}' cannot be read: {}", key, exception.toString());
            return Optional.empty();
        }
    }

    private static SparkleSystem read(JsonObject root) {
        Map<String, SparkleSystem.Parameter> parameters = new HashMap<>();
        Map<String, String> parameterDefaults = new HashMap<>();
        for (JsonElement element : array(root, "userParameters")) {
            JsonObject parameter = element.getAsJsonObject();
            String id = text(parameter, "id", "");
            String name = text(parameter, "name", id);
            if (!id.isEmpty()) {
                parameters.put(id, new SparkleSystem.Parameter(name, new ArrayList<>()));
                parameterDefaults.put(id, text(parameter, "value", ""));
            }
        }

        List<SparkleEmitter> emitters = new ArrayList<>();
        for (JsonElement element : array(root, "emitters")) {
            JsonObject emitterObject = element.getAsJsonObject();
            SparkleEmitter emitter = new SparkleEmitter();
            int index = emitters.size();
            for (JsonElement moduleElement : array(emitterObject, "modules")) {
                JsonObject module = moduleElement.getAsJsonObject();
                String kind = text(module, "kind", "");
                boolean enabled = !module.has("enabled") || module.get("enabled").getAsBoolean();
                emitter.enable(kind, enabled);
                if (!enabled || !module.has("values") || !module.get("values").isJsonObject()) {
                    continue;
                }

                for (Map.Entry<String, JsonElement> value : module.getAsJsonObject("values").entrySet()) {
                    String text = value.getValue().isJsonPrimitive() ? value.getValue().getAsString() : "";
                    if (text.startsWith("@")) {
                        // A user parameter: its value of the file now, the value sent by the server when the system plays.
                        String id = text.substring(1);
                        SparkleSystem.Parameter parameter = parameters.get(id);
                        if (parameter != null) {
                            parameter.bindings().add(new SparkleSystem.Binding(index, kind, value.getKey()));
                            emitter.set(kind, value.getKey(), parameterDefaults.get(id));
                        }
                    } else {
                        emitter.set(kind, value.getKey(), text);
                    }
                }
            }

            emitter.finish();
            emitters.add(emitter);
        }

        Map<String, SparkleSystem.Parameter> byName = new HashMap<>();
        for (SparkleSystem.Parameter parameter : parameters.values()) {
            byName.put(parameter.name().toLowerCase(Locale.ROOT), parameter);
        }

        return new SparkleSystem(List.copyOf(emitters), byName);
    }

    private static JsonArray array(JsonObject object, String name) {
        return object.has(name) && object.get(name).isJsonArray() ? object.getAsJsonArray(name) : new JsonArray();
    }

    private static String text(JsonObject object, String name, String fallback) {
        return object.has(name) && object.get(name).isJsonPrimitive() ? object.get(name).getAsString() : fallback;
    }
}
